#!/usr/bin/env python3
"""Bundle collision and map constants for rooms with recovered render assets."""
import hashlib
import json
from pathlib import Path
import struct
from cing_container import decode_member, decompress

ROOT = Path(__file__).resolve().parents[1]
NAMES = ["NONE"] + [f"R{x}" for x in range(101, 127)] + [f"R{x}" for x in range(201, 214)] + [f"R{x}" for x in range(301, 306)] + ["R401", "R402"]
# These rooms lack a normal search scene or still have unresolved render assets.
EXCLUDED = {0, 1, 20, 21, 42, 46}


def main():
    output = ROOT / "Sources/HotelDuskDuoKit/Resources/Original/GameData"
    manifest_path = output / "manifest.json"
    manifest = json.loads(manifest_path.read_text())
    code = (ROOT / "extracted/recovered_logic/binaries/arm9.bin").read_bytes()
    base = 0x02004000
    records = []
    for index, name in enumerate(NAMES):
        if index in EXCLUDED:
            continue
        source = ROOT / f"extracted/unpacked_wpf/map/{name}/{name}/{name}.col"
        member = source.read_bytes()
        decoded = decode_member(member)
        if decoded[:16] != b"MDF_COL_100" + bytes(5):
            raise ValueError(f"Unexpected collision header: {name}")
        payload = member[32:]
        (output / f"{name}.col").write_bytes(payload)
        manifest["files"] = [record for record in manifest["files"] if record["name"] != f"{name}.col"]
        manifest["files"].append({"name": f"{name}.col", "source": str(source.relative_to(ROOT)),
            "bytes": len(payload), "sha256": hashlib.sha256(payload).hexdigest(),
            "sourceMemberSHA256": hashlib.sha256(member).hexdigest(),
            "decodedSHA256": hashlib.sha256(decoded).hexdigest()})
        x, y = struct.unpack_from("<ii", code, 0x020E02AC - base + index * 8)
        scale = struct.unpack_from("<f", code, 0x020DFF60 - base + index * 4)[0]
        bitmap = (ROOT / f"Sources/HotelDuskDuoKit/Resources/OriginalBitmaps/map/fmapscr/{name}.bin").read_bytes()
        if bitmap[:3] == bytes.fromhex("123dda"):
            bitmap = decompress(bitmap)
        width, height = struct.unpack_from("<HH", bitmap, 4)
        area = 0 if index in (44, 45) else 1 if index in (16, 26, 31) else 2
        records.append(f'        {index}: .init(name: "{name}", origin: SIMD2({x}, {y + 8}), scale: {scale:.1f}, searchArea: {area}, compact: {str(width == height == 256).lower()}),')
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    swift = '''import Foundation

/// Generated by tools/recover_map_catalog.py from the original map tables.
/// Origins: 0x020E02AC. Scales: 0x020DFF60. Sizes: original floor-plan headers.
enum OriginalMapCatalog {
    struct Map {
        let name: String
        let origin: SIMD2<Float>
        let scale: Float
        let searchArea: UInt16
        let compact: Bool
    }

    static let maps: [Int16: Map] = [
''' + "\n".join(records) + '''
    ]
}
'''
    (ROOT / "Sources/HotelDuskDuoKit/Engine/Original/OriginalMapCatalog.swift").write_text(swift)
    print(f"Bundled {len(records)} maps")


if __name__ == "__main__":
    main()
